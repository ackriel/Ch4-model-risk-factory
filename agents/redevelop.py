def _artifact(model_id: str, suffix: str):
    return config.LEGACY_ARTIFACTS / f"{model_id}_r_{suffix}"


def obtain_legacy_outputs(model: dict) -> dict:
    mid = model["model_id"]
    rscript = shutil.which("Rscript")
    if rscript:
        proc = subprocess.run([rscript, model["source_file"], config.rel(config.LEGACY_ARTIFACTS)],
                              cwd=config.ROOT, capture_output=True, text=True, timeout=300)
        if proc.returncode != 0:
            raise RuntimeError(f"R script failed:\n{proc.stderr}")
        mode, note = "GENUINE_R_LIVE", "R script executed now with Rscript."
    elif _artifact(mid, "test_scores.csv").exists():
        mode, note = "GENUINE_R_RECORDED", ("Rscript not installed on this machine: using outputs "
                                            "recorded from a real R run (see run info).")
    else:
        return {"mode": "SIMULATED", "note": "No R and no recorded R outputs: legacy model "
                "SIMULATED in Python. This does not prove an R-to-Python migration."}
    run_info = {}
    info_file = _artifact(mid, "run_info.txt")
    if info_file.exists():
        run_info = dict(line.split("=", 1) for line in info_file.read_text().splitlines() if "=" in line)
    return {
        "mode": mode, "note": note, "r_run_info": run_info,
        "coefficients": pd.read_csv(_artifact(mid, "coefficients.csv")),
        "train_scores": pd.read_csv(_artifact(mid, "train_scores.csv")),
        "test_scores": pd.read_csv(_artifact(mid, "test_scores.csv")),
        "spec": pd.read_csv(_artifact(mid, "spec.csv"), keep_default_na=False),
    }


def spec_from_r_outputs(spec: pd.DataFrame) -> tuple[list[str], dict]:
    numeric = spec.loc[spec["type"] == "numeric", "variable"].tolist()
    factors = {}
    for var, grp in spec[spec["type"] == "factor"].groupby("variable", sort=False):
        factors[var] = grp.sort_values("level_order")["level"].tolist()
    return numeric, factors


def spec_from_r_source(path) -> tuple[list[str], dict]:
    """Fallback for SIMULATED mode: parse the specification out of the R code."""
    import re
    text = path.read_text()
    numeric = discover._r_string_vector(text, "numeric_vars")
    block = re.search(r"factor_levels\s*<-\s*list\((.*?)\n\)", text, flags=re.S).group(1)
    factors = {}
    for var, body in re.findall(r"(\w+)\s*=\s*c\((.*?)\)", block, flags=re.S):
        factors[var] = re.findall(r'"([^"]*)"', body)
    return numeric, factors


def generate_module(model: dict, numeric: list[str], factors: dict):
    config.REDEVELOPED_DIR.mkdir(parents=True, exist_ok=True)
    factors_src = "{\n" + "".join(f"    {k!r}: {v!r},\n" for k, v in factors.items()) + "}"
    code = MODULE_TEMPLATE.format(model_id=model["model_id"], source_file=model["source_file"],
                                  sha256=model["sha256"], target=model["target_variable"],
                                  numeric=numeric, factors=factors_src)
    path = config.REDEVELOPED_DIR / f"{model['model_id'].lower().replace('-', '_')}_logit.py"
    path.write_text(code)
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return path, module


def simulated_legacy(module, train: pd.DataFrame, test: pd.DataFrame) -> dict:
    from sklearn.linear_model import LogisticRegression
    X = module.RedevelopedLogit.design_matrix(train)
    lr = LogisticRegression(penalty=None, fit_intercept=False, max_iter=10000, tol=1e-12)
    lr.fit(X, train[module.TARGET])
    coefs = pd.DataFrame({"term": X.columns, "estimate": lr.coef_[0]})
    score = lambda df: lr.predict_proba(module.RedevelopedLogit.design_matrix(df)[X.columns])[:, 1]
    return {"coefficients": coefs,
            "train_scores": pd.DataFrame({"customer_id": train["customer_id"], "pd": score(train)}),
            "test_scores": pd.DataFrame({"customer_id": test["customer_id"], "pd": score(test)})}


def redevelop_model(model: dict) -> dict:
    mid = model["model_id"]
    train, test = data.load_split()
    legacy = obtain_legacy_outputs(model)

    if legacy["mode"] == "SIMULATED":
        numeric, factors = spec_from_r_source(config.ROOT / model["source_file"])
        spec_check = {"source": "parsed from R source code"}
    else:
        numeric, factors = spec_from_r_outputs(legacy["spec"])
        static = set(model["input_features"])
        spec_check = {"source": "specification exported by the R run",
                      "matches_discover_agent": static == set(numeric) | set(factors),
                      "variables": numeric + list(factors)}

    module_path, module = generate_module(model, numeric, factors)
    py_model = module.RedevelopedLogit().fit(train)
    py_coefs = py_model.coefficients()
    py_train = pd.DataFrame({"customer_id": train["customer_id"], "pd": py_model.predict_proba(train)})
    py_test = pd.DataFrame({"customer_id": test["customer_id"], "pd": py_model.predict_proba(test)})

    py_coefs.to_csv(config.REDEVELOPED_DIR / f"{mid}_python_coefficients.csv", index=False)
    py_train.to_csv(config.REDEVELOPED_DIR / f"{mid}_python_train_scores.csv", index=False)
    py_test.to_csv(config.REDEVELOPED_DIR / f"{mid}_python_test_scores.csv", index=False)

    if legacy["mode"] == "SIMULATED":
        legacy.update(simulated_legacy(module, train, test))

    coef_parity = parity.compare_coefficients(legacy["coefficients"], py_coefs)
    test_parity = parity.compare_predictions(legacy["test_scores"], py_test)
    train_parity = parity.compare_predictions(legacy["train_scores"], py_train)
    passed = coef_parity["passed"] and test_parity["passed"] and train_parity["passed"]

    report = {
        "model_id": mid, "model_name": model["model_name"],
        "generated_at": state.now(),
        "legacy_source": model["source_file"],
        "legacy_mode": legacy["mode"], "legacy_note": legacy["note"],
        "r_run_info": legacy.get("r_run_info", {}),
        "generated_python_module": config.rel(module_path),
        "python_fit_iterations": int(py_model.n_iter_),
        "specification_check": spec_check,
        "tolerance": config.PARITY_TOLERANCE,
        "coefficients": coef_parity,
        "test_predictions": test_parity,
        "train_predictions": train_parity,
        "parity_passed": bool(passed),
        "genuine_migration": legacy["mode"] != "SIMULATED",
        "verdict": ("PASS" if passed else "FAIL") + (" (SIMULATED - not a genuine R migration)"
                                                     if legacy["mode"] == "SIMULATED" else ""),
    }
    (config.REPORTS_DIR / f"{mid}_parity.json").write_text(json.dumps(report, indent=2))
    return report


def run() -> dict:
    config.ensure_dirs()
    inv = discover.load_inventory()
    targets = [m for m in inv["models"]
               if m["language"] == "R" and "logistic" in m["methodology"].lower()]
    if not targets:
        raise RuntimeError("No R logistic regression model found in the inventory.")
    results = {}
    for m in targets:
        r = redevelop_model(m)
        results[m["model_id"]] = {
            "verdict": r["verdict"], "mode": r["legacy_mode"],
            "max_abs_diff_test_pd": r["test_predictions"]["max_abs_diff"],
            "max_abs_diff_coefficients": r["coefficients"]["max_abs_diff"],
        }
    return {"models_redeveloped": len(results), "results": results}


def load_parity(model_id: str) -> dict | None:
    p = config.REPORTS_DIR / f"{model_id}_parity.json"
    return json.loads(p.read_text()) if p.exists() else None


if __name__ == "__main__":
    print(json.dumps(run(), indent=2, default=float))
